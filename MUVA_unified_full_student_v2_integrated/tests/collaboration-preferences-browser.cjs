const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core');
const out = process.env.MUVA_SCREENSHOT_DIR || 'docs/ui-verification/collaboration/planning-preferences-2026-10-31';
fs.mkdirSync(out, {recursive:true});
(async () => {
  const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:2048,height:1152}});
  const errors=[], consoleErrors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error') consoleErrors.push(m.text());});
  const base=process.env.MUVA_TEST_URL || 'http://127.0.0.1:5173';
  let storeUrl;
  const state=()=>page.evaluate(async url=>{const s=(await import(url)).useCollaborationStore.getState();return {mission:s.missionState,running:s.isRunning,cluster:s.clusterRunning,selected:s.selectedTaskGroup,notice:s.notice};},storeUrl);
  const shot=name=>page.screenshot({path:`${out}/${name}.png`,fullPage:true});
  const nav=name=>page.getByRole('navigation',{name:'实验三六步教学流程'}).getByRole('button',{name:new RegExp(name)}).click();
  const openResources=()=>page.getByRole('button',{name:'无人机资源管理',exact:true}).click();
  const resource=()=>page.getByRole('dialog',{name:'无人机资源管理',exact:true});
  try {
    await page.goto(`${base}/login`);
    await page.evaluate(()=>{sessionStorage.setItem('muva-mock-user','signed-in');sessionStorage.setItem('muva-user-role','student');});
    await page.goto(`${base}/experiments/collaboration`);
    await page.getByRole('button',{name:/进入教学模拟模式/}).click();
    storeUrl=await page.evaluate(()=>performance.getEntriesByType('resource').find(e=>new URL(e.name).pathname==='/src/stores/collaborationStore.ts').name);
    await page.evaluate(() => { window.preferenceWrites = 0; const original = Storage.prototype.setItem; Storage.prototype.setItem = function(key, value) { if(key === 'muva:collaboration:preferences:v1') window.preferenceWrites++; return original.call(this, key, value); }; });
    await nav('集群启动');await page.getByRole('button',{name:'启动集群',exact:true}).click();
    await page.waitForFunction(async url=>(await import(url)).useCollaborationStore.getState().clusterRunning,storeUrl);
    await nav('多任务协同指挥');await page.getByRole('button',{name:'展开指挥台',exact:true}).click();
    await page.getByRole('navigation',{name:'任务业务导航'}).getByRole('button',{name:'区域巡逻',exact:true}).click();
    await openResources();
    assert.equal(await resource().locator('tbody tr').count(),15);
    for(const id of ['uav101','uav102']) {
      const row=resource().locator('tbody tr').filter({has:page.getByText(id,{exact:true})});
      await row.getByRole('button',{name:`编辑${id}资源配置`}).click();
      const editor=page.getByRole('dialog',{name:`${id}编辑模拟资源配置`});
      await editor.getByRole('button',{name:/航线巡检组件/}).click();
      await editor.getByLabel('允许执行的任务').selectOption('区域巡逻');
      await editor.getByRole('button',{name:'添加任务'}).click();
      if(id==='uav101') {
        await editor.getByRole('button',{name:/模拟搜索组件/}).click();
        await editor.getByLabel('允许执行的任务').selectOption('目标搜索');
        await editor.getByRole('button',{name:'添加任务'}).click();
      }
      await editor.getByRole('button',{name:'保存配置'}).click();
      await row.getByRole('button',{name:`${id}加入区域巡逻`}).click();
    }
    const roleOptions=await resource().getByLabel('uav102在区域巡逻的角色',{exact:true}).locator('option').allTextContents();
    await resource().getByLabel('uav102在区域巡逻的角色',{exact:true}).selectOption({label:roleOptions[0]});
    await resource().getByLabel('资源编组任务').selectOption('group-2');
    await resource().getByRole('button',{name:'uav101加入目标搜索',exact:true}).click();
    assert.equal((await state()).selected,'group-1','resource tabs must not navigate the command task');
    await resource().getByLabel('资源编组任务').selectOption('group-1');
    await shot('01-resource-members-desktop');
    await page.setViewportSize({width:1366,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
    await shot('02-resource-members-1366');
    await page.setViewportSize({width:2048,height:1152});
    await resource().getByRole('button',{name:'完成配置',exact:true}).click();
    await page.getByRole('button',{name:'无人机编组',exact:true}).click();
    assert.equal(await page.getByRole('checkbox',{name:'选择uav102',exact:true}).isChecked(),true);
    await page.getByRole('checkbox',{name:'选择uav102',exact:true}).uncheck();
    await openResources();assert.equal(await resource().getByRole('button',{name:'uav102加入区域巡逻',exact:true}).count(),1);
    await resource().getByRole('button',{name:'uav102加入区域巡逻',exact:true}).click();
    await resource().getByRole('button',{name:'完成配置',exact:true}).click();
    await page.getByRole('button',{name:'任务参数',exact:true}).click();
    await page.getByLabel('扫描航线间距（m）',{exact:true}).fill('3');
    await page.getByRole('button',{name:'两点绘制矩形',exact:true}).click();
    const map=page.getByTestId('fleet-map');const b=await map.boundingBox();
    await page.mouse.click(b.x+b.width*.42,b.y+b.height*.36);
    await page.mouse.move(b.x+b.width*.69,b.y+b.height*.66);
    assert.equal(await page.locator('[data-rectangle-preview]').count(),1);
    await page.mouse.click(b.x+b.width*.69,b.y+b.height*.66);
    assert.equal((await state()).mission.groups[0].points.length,4);
    assert.equal((await state()).mission.groups[0].areaClosed,true);
    await page.getByRole('button',{name:'完成绘制',exact:true}).click();
    await page.getByRole('button',{name:'生成巡逻航线',exact:true}).click();
    const planned=(await state()).mission.groups[0].plan;
    assert.ok(planned,(await state()).notice);assert.equal(planned.routes.length,2);
    assert.ok(planned.routes.every(r=>r.waypoints.length>3),'actual serpentine waypoint sets, not a placeholder');
    assert.ok(await page.locator('[data-generated-waypoint="uav101"]').count()>2);
    await shot('03-serpentine-waypoints-desktop');
    await page.setViewportSize({width:1366,height:900});await page.waitForTimeout(300);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
    await shot('04-serpentine-waypoints-1366');await page.setViewportSize({width:2048,height:1152});
    await page.getByRole('button',{name:'检查并部署',exact:true}).click();
    await page.getByRole('button',{name:'下发模拟航线',exact:true}).click();
    await page.getByRole('button',{name:'模拟解锁',exact:true}).click();
    await page.getByRole('button',{name:'确认模拟起飞',exact:true}).click();
    await page.waitForFunction(async url=>(await import(url)).useCollaborationStore.getState().missionState.drones.some(d=>d.position.z>10),storeUrl);
    await page.getByRole('button',{name:'关闭地图图层',exact:true}).click();
    await shot('05-simulated-flight-tracks');
    const writes = await page.evaluate(() => window.preferenceWrites);
    await page.waitForTimeout(1200);
    assert.equal(await page.evaluate(() => window.preferenceWrites), writes, 'telemetry must not write configuration storage');
    // Refresh while airborne: retain configuration, never resume hardware or simulated flight.
    await page.reload();await page.waitForLoadState('networkidle');
    const restored=await state();
    assert.equal(restored.running,false);assert.equal(restored.cluster,false);
    assert.deepEqual(restored.mission.groups[0].drones,['uav101','uav102']);
    assert.deepEqual(restored.mission.groups[1].drones,['uav101']);
    assert.ok(restored.mission.groups.every(g=>!g.plan&&!g.runId&&!g.points.length));
    assert.ok(restored.mission.drones.every(d=>!d.armed&&!d.assignedTaskId&&d.connectionStatus==='DISCONNECTED'));
    assert.equal(restored.mission.drones[0].allowedTaskTypes.length,2);
    assert.deepEqual(errors,[]);
    const applicationConsoleErrors=consoleErrors.filter(e=>!/(net::ERR_|Failed to load resource|Failed to fetch|maplibre|AJAXError)/i.test(e));
    assert.deepEqual(applicationConsoleErrors,[]);
    fs.writeFileSync(`${out}/result.json`,JSON.stringify({status:'passed',tests:['15-row resources','dual-entry sync','task tabs preserve command selection','roles','rectangle drawing','actual snake routes and waypoints','simulated deployment and flight','refresh while airborne restores only configuration','desktop/narrow overflow'],pageErrors:errors,consoleErrors},null,2));
    console.log('PASS planning/preferences browser review',out);
  } catch(e) {await shot('failure').catch(()=>{});console.error(e);process.exitCode=1;} finally {await browser.close();}
})();
