const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core');
const out = process.env.MUVA_SCREENSHOT_DIR || 'docs/ui-verification/collaboration/compact-startup-2026-10-31';
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1829, height: 1120 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  const base = process.env.MUVA_TEST_URL || 'http://127.0.0.1:5175';
  const nav = (label) => page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: new RegExp(label) });
  const shot = (label) => page.screenshot({ path: `${out}/${label}.png`, fullPage: true });
  try {
    await page.goto(`${base}/login`);
    await page.evaluate(() => { sessionStorage.setItem('muva-mock-user', 'signed-in'); sessionStorage.setItem('muva-user-role', 'student'); });
    await page.goto(`${base}/experiments/collaboration`);
    await page.getByRole('button', { name: '进入教学模拟模式', exact: true }).click();
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /集群启动/ }).click();
    const storeUrl = await page.evaluate(() => performance.getEntriesByType('resource').find((e) => new URL(e.name).pathname === '/src/stores/collaborationStore.ts')?.name);
    assert.ok(storeUrl);
    const read = () => page.evaluate(async (url) => {
      const s = (await import(url)).useCollaborationStore.getState();
      return { step: s.currentStep, cluster: s.clusterRunning, starting: s.clusterStarting, running: s.isRunning, progress: s.bootProgress, selected: s.selectedDrone, layout: s.arrayLayout, drones: s.missionState.drones, nodes: s.communicationNodes, events: s.events };
    }, storeUrl);
    await page.clock.install();
    await page.clock.pauseAt(new Date(Date.now() + 1000));
    assert.equal(await page.getByRole('button', { name: /^查看uav\d+启动状态$/ }).count(), 15);
    assert.equal(await page.getByRole('button', { name: /^在阵列中选择uav/ }).count(), 15);
    await shot('01-startup-idle-desktop');
    await page.getByRole('spinbutton', { name: '中心 X', exact: true }).fill('12');
    await page.getByRole('spinbutton', { name: '行间距', exact: true }).fill('32');
    let s = await read();
    assert.equal(s.layout.centerX, 12); assert.equal(s.layout.rowSpacing, 32);
    assert.equal(new Set(s.drones.map((d) => d.position.x)).size, 5);
    assert.equal(new Set(s.drones.map((d) => d.position.y)).size, 3);
    assert.equal(s.drones[0].homePosition.x, -36); assert.equal(s.drones[0].homePosition.y, 32);
    await page.getByRole('button', { name: '查看uav115启动状态', exact: true }).click();
    assert.equal((await read()).selected, 'uav115');
    assert.equal(await page.getByRole('button', { name: '在阵列中选择uav115', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: '在阵列中选择uav110', exact: true }).click();
    assert.equal((await read()).selected, 'uav110');
    await page.getByRole('button', { name: '在阵列中选择uav101', exact: true }).focus();
    await page.keyboard.press('Enter'); assert.equal((await read()).selected, 'uav101');
    const marker = page.getByRole('button', { name: '在阵列中选择uav101', exact: true });
    const before = await marker.getAttribute('transform');
    await page.getByRole('button', { name: '放大阵列预览', exact: true }).click();
    assert.notEqual(await marker.getAttribute('transform'), before);
    await page.getByRole('button', { name: '缩小阵列预览', exact: true }).click();
    await page.getByRole('button', { name: '适配阵列预览', exact: true }).click();
    assert.equal(await marker.getAttribute('transform'), before);
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    s = await read(); assert.equal(s.starting, true); assert.equal(s.running, false);
    assert.equal(await page.getByRole('button', { name: '正在启动集群', exact: true }).isDisabled(), true);
    assert.equal(await page.getByRole('spinbutton', { name: '中心 X', exact: true }).isDisabled(), true);
    await page.clock.runFor(500);
    assert.equal((await read()).progress, 25);
    await shot('02-startup-progress');
    await page.clock.runFor(1800);
    s = await read();
    assert.equal(s.cluster, true); assert.equal(s.running, false); assert.equal(s.progress, 100);
    assert.ok(s.drones.every((d, i) => d.id === `uav${i + 101}` && d.raspberryPiIp === `192.168.10.${i + 101}` && d.instanceStatus === 'STANDBY' && !d.armed && !d.assignedTaskId));
    assert.ok(s.nodes.every((n) => n.source === 'Mock' && n.network === '模拟在线' && n.heartbeatAt));
    await page.getByRole('heading', { name: '启动配置', exact: true }).scrollIntoViewIfNeeded();
    await shot('03-startup-ready-desktop');
    await page.getByRole('heading', { name: '启动进度' }).scrollIntoViewIfNeeded();
    await shot('04-startup-ready-monitor');
    for (const [width, height] of [[2048, 1152], [1600, 1000], [1280, 900], [768, 1024], [390, 844]]) {
      await page.setViewportSize({ width, height });
      await page.getByRole('heading', { name: '启动配置', exact: true }).scrollIntoViewIfNeeded();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `no horizontal overflow at ${width}`);
      await shot(`startup-${width}`);
      await page.getByRole('heading', { name: '起飞阵列预览', exact: true }).scrollIntoViewIfNeeded();
      await shot(`startup-${width}-formation`);
      await page.getByRole('heading', { name: '启动进度', exact: true }).scrollIntoViewIfNeeded();
      await shot(`startup-${width}-monitor`);
      assert.equal(await page.getByRole('button', { name: /^查看uav\d+启动状态$/ }).count(), 15);
    }
    await page.setViewportSize({ width: 1829, height: 1120 });
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /通信组网/ }).click(); assert.equal((await read()).step, 2);
    await nav('集群启动').click(); s = await read(); assert.equal(s.cluster, true); assert.equal(s.selected, 'uav101'); assert.equal(s.layout.centerX, 12);
    page.once('dialog', (d) => d.dismiss());
    await page.getByRole('button', { name: '停止集群', exact: true }).click(); assert.equal((await read()).cluster, true);
    page.once('dialog', (d) => d.accept());
    await page.getByRole('button', { name: '停止集群', exact: true }).click();
    s = await read(); assert.equal(s.cluster, false); assert.ok(s.drones.every((d) => d.instanceStatus === 'STOPPED'));
    assert.equal(await page.getByRole('spinbutton', { name: '中心 X', exact: true }).isDisabled(), false);
    await shot('05-startup-stopped');
    await page.getByRole('button', { name: '启动集群', exact: true }).click(); await page.clock.runFor(2200);
    assert.equal((await read()).cluster, true); assert.equal((await read()).running, false);
    assert.deepEqual(errors, []);
    fs.writeFileSync(`${out}/result.json`, JSON.stringify({ passed: true, viewports: [2048, 1829, 1600, 1280, 768, 390], checks: ['15 instance cards and Home markers', 'array inputs update resources and preview', 'card/map two-way selection and keyboard', 'preview zoom and fit', 'runtime startup progress and disabled repeat submission', '15 correct drone/Pi pairs ready, unarmed and unassigned', 'no automatic task', 'navigation retains state', 'stop cancellation and confirmation', 'restart', 'no horizontal overflow', 'no console errors'], errors }, null, 2));
    console.log('PASS: step 2 startup UI, configuration, map selection, lifecycle, stop confirmation, 6 viewports');
  } catch (e) { await shot('failure'); throw e; }
  finally { await browser.close(); }
})().catch((e) => { console.error(e); process.exitCode = 1; });
