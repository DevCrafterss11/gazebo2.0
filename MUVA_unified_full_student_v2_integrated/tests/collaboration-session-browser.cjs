/* In-app navigation preserves a live Mock session; full reload starts a clean one. */
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
  const errors = [], messages = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', async dialog => { messages.push(dialog.message()); await dialog.accept(); });
  const base = process.env.MUVA_TEST_URL || 'http://127.0.0.1:5175';
  try {
    await page.goto(`${base}/login`);
    await page.evaluate(() => { sessionStorage.setItem('muva-mock-user', 'signed-in'); sessionStorage.setItem('muva-user-role', 'student'); sessionStorage.setItem('muva-username', 'student01'); });
    await page.goto(`${base}/experiments/collaboration`);
    const storeUrl = await page.evaluate(() => performance.getEntriesByType('resource').find(e => new URL(e.name).pathname === '/src/stores/collaborationStore.ts')?.name);
    assert.ok(storeUrl);
    const read = () => page.evaluate(async url => { const s = (await import(url)).useCollaborationStore.getState(); return { step: s.currentStep, running: s.isRunning, cluster: s.clusterRunning, groups: s.missionState.groups, runs: s.schedulerState.activeRuns, leases: s.schedulerState.activeLeases, stats: s.schedulerState.stats, records: s.records, notice: s.notice }; }, storeUrl);
    const steps = page.getByRole('navigation', { name: '实验三六步教学流程' });
    await page.getByRole('button', { name: /进入教学模拟模式/ }).click();
    await steps.getByRole('button', { name: /集群启动/ }).click();
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    await page.waitForTimeout(2400);
    await steps.getByRole('button', { name: /多任务协同指挥/ }).click();
    await page.getByRole('button', { name: '展开指挥台' }).click();
    const view = page.getByRole('dialog', { name: '独立任务全屏工作区' });
    await view.getByRole('checkbox', { name: '并发调度模式' }).check();
    await view.getByRole('navigation', { name: '任务业务导航' }).getByRole('button', { name: '区域巡逻', exact: true }).click();
    const examples = view.locator('summary').filter({ hasText: '模拟演练与验收场景' });
    if (!await examples.evaluate(e => e.parentElement.open)) await examples.click();
    await view.getByRole('button', { name: '载入本任务模拟示例' }).click();
    await view.getByRole('button', { name: '生成巡逻航线' }).click();
    await view.getByRole('button', { name: '检查并部署' }).click();
    const deploy = page.getByRole('dialog', { name: '当前任务确认' });
    await deploy.getByRole('button', { name: '下发模拟航线' }).click();
    await deploy.getByRole('button', { name: '模拟解锁' }).click();
    if (await deploy.getByRole('checkbox').count()) await deploy.getByRole('checkbox').check();
    await deploy.getByRole('button', { name: /模拟起飞/ }).click();
    assert.equal((await read()).runs.length, 1);
    await view.getByRole('button', { name: '返回教学页面' }).click();
    await page.getByRole('button', { name: '重新开始' }).click();
    assert.match(messages.at(-1), /等待无人机安全落地/);
    assert.equal((await read()).runs.length, 1, 'reset cannot erase live leases');
    await page.getByRole('link', { name: '实验中心', exact: true }).last().click();
    await page.locator('a[href="/experiments/collaboration"]').first().click();
    assert.equal((await read()).step, 4);
    assert.equal((await read()).runs.length, 1, 'SPA navigation preserves live session');
    await page.getByRole('button', { name: '展开指挥台' }).click();
    assert.equal(await view.count(), 1);
    await page.reload();
    const fresh = await read();
    assert.equal(fresh.step, 0);
    assert.equal(fresh.cluster, false);
    assert.equal(fresh.runs.length, 0);
    assert.equal(fresh.leases.length, 0);
    assert.equal(fresh.records.length, 0);
    assert.equal(fresh.stats.currentConcurrency, 0);
    assert.equal(fresh.groups[0].drones.length, 3, 'resource/team preferences survive refresh');
    assert.equal(fresh.groups[0].plan, undefined, 'flight plan is session-only');
    assert.match(await page.getByRole('status').allTextContents().then(v => v.join(' ')), /旧租赁已清理/);
    assert.equal(await page.evaluate(() => localStorage.getItem('muva-collaboration-scheduler-v1')), null);
    // Standard (non-scheduler) flight must also warn after an interrupted reload.
    await page.getByRole('button', { name: /进入教学模拟模式/ }).click();
    await steps.getByRole('button', { name: /集群启动/ }).click();
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    await page.waitForTimeout(2400);
    await steps.getByRole('button', { name: /多任务协同指挥/ }).click();
    await page.getByRole('button', { name: '展开指挥台' }).click();
    await view.getByRole('navigation', { name: '任务业务导航' }).getByRole('button', { name: '区域巡逻', exact: true }).click();
    if (!await examples.evaluate(e => e.parentElement.open)) await examples.click();
    await view.getByRole('button', { name: '载入本任务模拟示例' }).click();
    await view.getByRole('button', { name: '生成巡逻航线' }).click();
    await view.getByRole('button', { name: '检查并部署' }).click();
    await deploy.getByRole('button', { name: '下发模拟航线' }).click();
    await deploy.getByRole('button', { name: '模拟解锁' }).click();
    if (await deploy.getByRole('checkbox').count()) await deploy.getByRole('checkbox').check();
    await deploy.getByRole('button', { name: /模拟起飞/ }).click();
    assert.equal((await read()).running, true);
    await page.reload();
    assert.match(await page.getByRole('status').allTextContents().then(v => v.join(' ')), /上次飞行无法恢复/);
    assert.equal((await read()).running, false);

    // Logout during an actual flight must wait for RTL; the next account must see a clean session.
    await page.getByRole('button', { name: /进入教学模拟模式/ }).click();
    await steps.getByRole('button', { name: /集群启动/ }).click();
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    await page.waitForTimeout(2400);
    await steps.getByRole('button', { name: /多任务协同指挥/ }).click();
    await page.getByRole('button', { name: '展开指挥台' }).click();
    await view.getByRole('navigation', { name: '任务业务导航' }).getByRole('button', { name: '区域巡逻', exact: true }).click();
    if (!await examples.evaluate(e => e.parentElement.open)) await examples.click();
    await view.getByRole('button', { name: '载入本任务模拟示例' }).click();
    await view.getByRole('button', { name: '生成巡逻航线' }).click();
    await view.getByRole('button', { name: '检查并部署' }).click();
    await deploy.getByRole('button', { name: '下发模拟航线' }).click();
    await deploy.getByRole('button', { name: '模拟解锁' }).click();
    if (await deploy.getByRole('checkbox').count()) await deploy.getByRole('checkbox').check();
    await deploy.getByRole('button', { name: /模拟起飞/ }).click();
    await view.getByRole('button', { name: '返回教学页面' }).click();
    await page.getByRole('button', { name: '张三' }).click();
    await page.getByRole('menuitem', { name: '退出登录' }).click();
    await page.getByRole('button', { name: '确定退出' }).click();
    await page.getByRole('button', { name: '等待模拟飞机安全落地…' }).waitFor();
    await page.waitForURL('**/login', { timeout: 90000 });
    assert.equal((await read()).records.length, 0);
    assert.equal((await read()).leases.length, 0);
    await page.getByRole('button', { name: /教师/ }).first().click();
    await page.getByRole('button', { name: '登录教师端' }).click();
    await page.waitForURL('**/teacher/dashboard');
    assert.equal((await read()).groups[0].drones.length, 0, 'teacher must not inherit student team');
    await page.getByRole('button', { name: '张老师' }).click();
    await page.getByRole('menuitem', { name: '退出登录' }).click();
    await page.getByRole('button', { name: '确定退出' }).click();
    await page.waitForURL('**/login');
    await page.getByRole('button', { name: /学生/ }).first().click();
    await page.getByRole('button', { name: '登录学生端' }).click();
    await page.waitForURL('**/dashboard');
    await page.goto(`${base}/experiments/collaboration`);
    assert.equal((await read()).groups[0].drones.length, 3, 'student preferences survive own logout');
    // Direct account change through the login action (without pressing Logout) also isolates a live flight.
    await page.evaluate(async url => {
      const { useCollaborationStore } = await import(url);
      const s = () => useCollaborationStore.getState();
      s().enterSimulation(); s().startCluster();
    }, storeUrl);
    await page.waitForTimeout(2400);
    await page.evaluate(async url => {
      const { useCollaborationStore } = await import(url);
      const s = () => useCollaborationStore.getState();
      s().selectTaskGroup('group-1'); s().loadTaskExample(); s().generateTaskPlan();
      s().prepareTask(); s().distributeTask(); s().armTask();
      s().startExecution();
    }, storeUrl);
    assert.equal((await read()).running, true);
    const authUrl = await page.evaluate(() => performance.getEntriesByType('resource').find(e => new URL(e.name).pathname === '/src/stores/authStore.ts')?.name);
    assert.ok(authUrl);
    const switched = await page.evaluate(async url => (await import(url)).useAuthStore.getState().login({ username: 'teacher01', password: 'teacher123', role: 'teacher' }), authUrl);
    assert.equal(switched.ok, true);
    assert.equal((await read()).running, false);
    assert.equal((await read()).leases.length, 0);
    assert.equal((await read()).groups[0].drones.length, 0);
    const restart = await page.evaluate(async url => (await import(url)).useAuthStore.getState().login({ username: 'student01', password: 'student123', role: 'student' }), authUrl);
    assert.equal(restart.ok, true);
    await page.evaluate(async url => { const s = (await import(url)).useCollaborationStore.getState(); s.enterSimulation(); s.startCluster(); }, storeUrl);
    await page.evaluate(async url => (await import(url)).useAuthStore.getState().logout(), authUrl);
    await page.waitForTimeout(2400);
    assert.equal((await read()).cluster, false, 'late startup callback cannot resurrect fleet after logout');
    assert.equal((await read()).leases.length, 0);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, spaPreserved: true, reloadClean: true, standardReloadWarned: true, logoutLanded: true, accountsIsolated: true, directSwitchSafe: true, startupLogoutSafe: true }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
