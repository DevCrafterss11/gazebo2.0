const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core');
const out = process.env.MUVA_SCREENSHOT_DIR || 'docs/ui-verification/collaboration/map-command-focus-2026-10-31';
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  let accept = false;
  page.on('dialog', (d) => accept ? d.accept() : d.dismiss());
  let storeUrl;
  const base = process.env.MUVA_TEST_URL || 'http://127.0.0.1:5175';
  const read = () => page.evaluate(async (url) => {
    const s = (await import(url)).useCollaborationStore.getState();
    return { mission: s.missionState, running: s.isRunning, cluster: s.clusterRunning, events: s.events, selected: s.selectedDrone, records: s.records, step: s.currentStep };
  }, storeUrl);
  const view = page.getByRole('dialog', { name: '独立任务全屏工作区', exact: true });
  const shot = (name) => page.screenshot({ path: `${out}/${name}.png`, fullPage: true });
  const checkOverflow = async () => {
    const size = await view.evaluate((d) => ({ width: d.clientWidth, scroll: d.scrollWidth, page: document.documentElement.scrollWidth, window: innerWidth }));
    assert.ok(size.scroll <= size.width + 2 && size.page <= size.window + 2, `overflow ${JSON.stringify(size)}`);
    const geometry = await view.getByTestId('fleet-map').boundingBox();
    assert.ok(geometry.height >= 220, 'map retains usable height');
  };
  try {
    await page.addInitScript(() => performance.setResourceTimingBufferSize(5000));
    await page.goto(`${base}/login`);
    await page.evaluate(() => { sessionStorage.setItem('muva-mock-user', 'signed-in'); sessionStorage.setItem('muva-user-role', 'student'); });
    await page.goto(`${base}/experiments/collaboration`);
    await page.getByRole('button', { name: /进入教学模拟模式/ }).waitFor();
    storeUrl = await page.evaluate(() => performance.getEntriesByType('resource').find((e) => new URL(e.name).pathname === '/src/stores/collaborationStore.ts')?.name);
    assert.ok(storeUrl);
    await page.clock.install(); await page.clock.pauseAt(new Date(Date.now() + 1000));
    await page.getByRole('button', { name: /进入教学模拟模式/ }).click();
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /集群启动/ }).click();
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    await page.clock.runFor(2200);
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /多任务协同指挥/ }).click();
    await shot('01-existing-workspace');
    await page.getByRole('button', { name: '展开指挥台' }).click();
    await view.waitFor();
    await view.getByRole('button', { name: '实时遥测', exact: true }).click();
    assert.equal(await view.locator('[data-testid^="telemetry-uav"]').count(), 15);
    assert.equal(await view.locator('[data-testid^="marker-uav"]').count(), 15);
    assert.equal((await read()).running, false);
    await view.getByRole('button', { name: '定位遥测uav115', exact: true }).click();
    assert.equal((await read()).selected, 'uav115');
    await view.getByTitle('自动适配视野').click();
    await view.getByRole('button', { name: '关闭地图图层' }).click();
    await view.getByTestId('marker-uav101').click(); assert.equal((await read()).selected, 'uav101');
    await view.getByTitle('自动适配视野').click();
    await checkOverflow(); await shot('02-global-desktop');
    await view.getByRole('button', { name: '无人机资源管理', exact: true }).click();
    const resources = page.getByRole('dialog', { name: '无人机资源管理', exact: true });
    for (let n = 101; n <= 103; n++) {
      const row = resources.locator('tr').filter({ hasText: `uav${n}` });
      await row.getByRole('button', { name: `编辑uav${n}资源配置` }).click();
      const editor = page.getByRole('dialog', { name: `uav${n}编辑模拟资源配置` });
      await editor.getByRole('button', { name: /航线巡检组件/ }).click();
      await editor.getByRole('button', { name: '添加任务' }).click();
      await editor.getByRole('button', { name: '保存配置' }).click();
    }
    await resources.getByRole('button', { name: '完成配置' }).click();
    await view.getByRole('navigation', { name: '任务业务导航' }).getByRole('button', { name: '区域巡逻', exact: true }).click();
    await view.getByRole('button', { name: '无人机编组', exact: true }).click();
    for (let n = 101; n <= 103; n++) await view.getByLabel(`选择uav${n}`, { exact: true }).check();
    await view.getByLabel('uav103任务角色', { exact: true }).selectOption('侦察机');
    await view.getByRole('button', { name: '关闭地图图层' }).click();
    await view.getByRole('button', { name: /收起任务面板|展开任务面板/ }).click();
    await view.getByLabel('地图编辑工具').selectOption('point');
    const map = await view.getByTestId('fleet-map').boundingBox();
    for (const [x,y] of [[.3,.3],[.7,.3],[.7,.7],[.4,.63]]) await page.mouse.click(map.x + x * map.width, map.y + y * map.height);
    await view.getByLabel('地图编辑工具').selectOption('pan');
    assert.equal((await read()).mission.groups[0].points.length, 4);
    await view.getByRole('button', { name: '开始区域巡逻', exact: true }).click();
    await page.getByRole('dialog', { name: '当前任务确认', exact: true }).waitFor();
    assert.equal((await read()).running, false);
    await page.keyboard.press('Escape');
    assert.equal(await view.count(), 1, 'Escape dismisses confirmation before the view');
    await view.getByRole('button', { name: '开始区域巡逻', exact: true }).click();
    await page.getByRole('button', { name: '确认并开始当前任务', exact: true }).click();
    await page.clock.runFor(3000);
    let state = await read(); assert.equal(state.running, true);
    assert.equal(state.mission.groups.filter((g) => g.lifecycle === '执行中').length, 1);
    assert.ok(state.mission.drones[0].trajectory.length > 0);
    const before = state.mission.drones[0];
    await page.clock.runFor(1500);
    state = await read();
    assert.ok(state.mission.drones[0].updatedAt > before.updatedAt);
    assert.notDeepEqual(state.mission.drones[0].position, before.position);
    await view.getByRole('button', { name: '暂停任务', exact: true }).click();
    const paused = await read(); await page.clock.runFor(3000);
    state = await read(); assert.equal(state.mission.groups[0].progress, paused.mission.groups[0].progress);
    assert.deepEqual(state.mission.drones.map((d) => d.position), paused.mission.drones.map((d) => d.position));
    await shot('03-paused-desktop');
    await view.getByRole('button', { name: '继续任务', exact: true }).click();
    await page.clock.runFor(1000);
    await view.getByRole('button', { name: '实时遥测', exact: true }).click();
    await view.getByRole('button', { name: '定位遥测uav102', exact: true }).click();
    await view.getByTestId('marker-uav102').click();
    await view.getByRole('region', { name: 'uav102操作面板' }).getByRole('button', { name: '遥测详情' }).click();
    assert.equal((await read()).step, 4, 'details stay inside independent view');
    const selected = view.getByRole('region', { name: '选中无人机实时详情' });
    // Sections with accessible names are exposed as regions.
    await selected.getByRole('button', { name: '单机模拟返航', exact: true }).click();
    assert.equal((await read()).mission.drones[1].instanceStatus, 'FLYING', 'cancel RTL has no effect');
    accept = true;
    await selected.getByRole('button', { name: '单机模拟返航', exact: true }).click();
    state = await read(); assert.equal(state.mission.drones[1].instanceStatus, 'RETURNING');
    assert.equal(state.mission.drones[0].instanceStatus, 'FLYING');
    await page.clock.runFor(1500);
    assert.ok((await read()).mission.drones[1].returnTrajectory.length > 0);
    await shot('04-single-return');
    await page.keyboard.press('Escape'); // close telemetry layer first
    await page.keyboard.press('Escape');
    await view.waitFor({ state: 'detached' });
    assert.equal((await read()).running, true);
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '展开指挥台');
    const closed = await read(); await page.clock.runFor(1000);
    assert.ok((await read()).mission.drones[0].updatedAt > closed.mission.drones[0].updatedAt);
    await page.getByRole('button', { name: '展开指挥台' }).click();
    await view.getByRole('button', { name: '实时遥测', exact: true }).click();
    assert.equal(await view.locator('[data-testid^="telemetry-uav"]').count(), 15);
    assert.equal((await read()).running, true);
    for (const [width, height] of [[1920,1080],[1366,768],[768,1024],[390,844]]) {
      await page.setViewportSize({ width, height });
      await checkOverflow();
      await view.getByTestId('fleet-map').scrollIntoViewIfNeeded();
      await shot(`05-responsive-${width}`);
      if (width === 390) {
        await view.getByRole('region', { name: '选中无人机实时详情' }).scrollIntoViewIfNeeded(); await shot('05-narrow-details');
        await view.getByTestId('telemetry-uav102').scrollIntoViewIfNeeded(); await shot('05-narrow-telemetry');
      }
    }
    await page.setViewportSize({ width: 1600, height: 1000 });
    for (let i = 0; i < 200 && (await read()).running; i++) await page.clock.runFor(1000);
    state = await read(); assert.equal(state.running, false); assert.equal(state.cluster, true); assert.equal(state.records.length, 1);
    assert.ok(state.records[0].drones[0].trajectory.length > 0);
    await view.getByTestId('fleet-map').scrollIntoViewIfNeeded();
    await shot('06-result-desktop');
    await view.getByRole('button', { name: '返回配置 / 再次执行', exact: true }).click();
    await view.getByRole('button', { name: '开始区域巡逻', exact: true }).click();
    await page.getByRole('button', { name: '确认并开始当前任务', exact: true }).click();
    await page.clock.runFor(1500);
    accept = false;
    await view.getByRole('button', { name: '终止任务', exact: true }).click();
    assert.equal((await read()).mission.groups[0].lifecycle, '执行中', 'cancel termination keeps task running');
    accept = true;
    await view.getByRole('button', { name: '终止任务', exact: true }).click();
    for (let i = 0; i < 100 && (await read()).running; i++) await page.clock.runFor(1000);
    assert.equal((await read()).mission.groups[0].lifecycle, '已终止');
    await view.getByRole('button', { name: '返回教学页面', exact: true }).click();
    assert.equal((await read()).records.length, 2);
    assert.equal((await read()).cluster, true);
    assert.deepEqual(errors, []);
    console.log('PASS: independent command view, 15 live telemetry cards/markers, shared state, task confirmation/control, RTL, desktop/narrow layouts, safe completion, focus restoration; no browser errors.');
  } finally { await browser.close(); }
})().catch((e) => { console.error(e); process.exitCode = 1; });
