const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core');
const out = process.env.MUVA_SCREENSHOT_DIR || 'docs/ui-verification/collaboration/resource-simplified-2026-11-01';
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 2048, height: 1152 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if (e.type() === 'error' && !/(net::ERR_|Failed to load resource|Failed to fetch|maplibre|AJAXError)/i.test(e.text())) errors.push(e.text()); });
  const resource = () => page.getByRole('dialog', { name: '无人机资源管理', exact: true });
  const editor = (id = 'uav101') => page.getByRole('dialog', { name: `${id}编辑模拟资源配置` });
  const base = process.env.MUVA_TEST_URL || 'http://127.0.0.1:5173';
  try {
    await page.goto(`${base}/login`);
    await page.evaluate(() => { sessionStorage.setItem('muva-mock-user', 'signed-in'); sessionStorage.setItem('muva-user-role', 'student'); });
    await page.goto(`${base}/experiments/collaboration`);
    await page.getByRole('button', { name: /进入教学模拟模式/ }).click();
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /集群启动/ }).click();
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    await page.waitForTimeout(2300);
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /多任务协同指挥/ }).click();
    await page.getByRole('button', { name: '展开指挥台', exact: true }).click();
    await page.getByRole('button', { name: '无人机资源管理', exact: true }).click();
    assert.equal(await resource().locator('tbody tr').count(), 15);
    assert.equal(await resource().getByRole('button', { name: '定位 / 详情' }).count(), 0);
    await resource().getByLabel('资源编组任务').selectOption('group-4');
    await resource().getByRole('button', { name: '编辑uav101资源配置' }).click();
    assert.equal(await editor().getByLabel('添加任务').inputValue(), '物资运输');
    await editor().getByLabel('选择机型').selectOption('Hexa 运输型');
    await editor().getByRole('button', { name: '加入任务', exact: true }).first().click();
    assert.match(await editor().getByText('物资运输', { exact: true }).last().locator('..').innerText(), /已加入/);
    await page.screenshot({ path: `${out}/00-editor-default-desktop.png`, fullPage: true });
    await page.setViewportSize({ width: 1366, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.screenshot({ path: `${out}/00b-editor-default-1366.png`, fullPage: true });
    await page.setViewportSize({ width: 2048, height: 1152 });
    await editor().getByLabel('选择机型').selectOption('X500 搜索型');
    assert.equal(await editor().getByRole('button', { name: '保存配置' }).isDisabled(), true);
    assert.match(await editor().getByRole('alert').innerText(), /不适用物资运输/);
    await editor().getByLabel('选择机型').selectOption('Hexa 运输型');
    await editor().getByRole('button', { name: '保存配置' }).click();
    assert.ok(await resource().getByRole('button', { name: 'uav101移出物资运输' }).isEnabled());
    assert.equal(await resource().getByLabel('uav101在物资运输的角色').count(), 0);
    await resource().getByLabel('资源编组任务').selectOption('group-2');
    await resource().getByRole('button', { name: '编辑uav102资源配置' }).click();
    await editor('uav102').getByLabel('选择机型').selectOption('X500 搜索型');
    await editor('uav102').getByRole('button', { name: '加入任务', exact: true }).first().click();
    await editor('uav102').getByRole('button', { name: '保存配置' }).click();
    assert.ok(await resource().getByRole('button', { name: 'uav102移出目标搜索' }).isEnabled());
    await resource().getByLabel('资源编组任务').selectOption('group-4');
    await page.setViewportSize({ width: 1366, height: 900 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.screenshot({ path: `${out}/02-inventory-1366.png`, fullPage: true });
    await resource().getByRole('button', { name: '完成配置' }).click();
    await page.getByRole('navigation', { name: '任务业务导航' }).getByRole('button', { name: '物资运输', exact: true }).click();
    await page.getByRole('button', { name: '无人机编组', exact: true }).click();
    const membersLayer = page.getByRole('region', { name: '无人机编组图层' });
    assert.equal(await membersLayer.getByLabel('选择uav101', { exact: true }).isChecked(), true);
    assert.equal(await membersLayer.getByLabel('选择uav103', { exact: true }).isVisible(), false);
    await membersLayer.getByText('查看其他资源（14 架）').click();
    assert.equal(await membersLayer.getByLabel('选择uav103', { exact: true }).isVisible(), true);
    await membersLayer.getByText('查看其他资源（14 架）').click();
    assert.equal(await membersLayer.locator('details').last().getAttribute('open'), null);
    await page.screenshot({ path: `${out}/03-members-default-1366.png`, fullPage: true });
    await membersLayer.getByText('特殊分工（可选）').click();
    assert.equal(await membersLayer.getByLabel('uav101任务角色').inputValue(), '运输机');
    await membersLayer.getByLabel('uav101任务角色').selectOption('护航机');
    assert.equal(await membersLayer.getByLabel('uav101任务角色').inputValue(), '护航机');
    await page.screenshot({ path: `${out}/04-members-advanced-1366.png`, fullPage: true });
    await page.reload();
    await page.getByRole('button', { name: /进入教学模拟模式/ }).click();
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /集群启动/ }).click();
    await page.getByRole('button', { name: '启动集群', exact: true }).click();
    await page.waitForTimeout(2300);
    await page.getByRole('navigation', { name: '实验三六步教学流程' }).getByRole('button', { name: /多任务协同指挥/ }).click();
    await page.getByRole('button', { name: '展开指挥台', exact: true }).click();
    await page.getByRole('button', { name: '无人机资源管理', exact: true }).click();
    await resource().getByLabel('资源编组任务').selectOption('group-4');
    assert.ok(await resource().getByRole('button', { name: 'uav101移出物资运输' }).count());
    assert.match(await resource().locator('tbody tr').first().innerText(), /Hexa 运输型/);
    await resource().getByLabel('资源编组任务').selectOption('group-2');
    assert.ok(await resource().getByRole('button', { name: 'uav102移出目标搜索' }).count());
    assert.deepEqual(errors, []);
    console.log('PASS experiment-three resource editor', out);
  } catch (e) { console.error(e); process.exitCode = 1; }
  finally { await browser.close(); }
})();
